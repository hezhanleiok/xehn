// Mode B (Clash subscription) renders its own complete config.yaml. Mode A
// keeps using renderClientConfig unchanged: the two modes must never share a
// branch, otherwise a subscription import could silently alter the WARP path.
//
// Layering: imported proxy = base / first hop; an optional OpenVPN or Psiphon
// exit is chained ON TOP of it with dialer-proxy. No WARP outbound is emitted,
// and no dialer-proxy is injected into the imported proxies themselves (that
// would create a loop).
const subBaseGroup = "SUB-BASE"
const subExitGroup = "SUB-EXIT"

// renderSubscriptionConfig builds the mode B config. Fields come from
// subscribe.go's ProxySpec (already whitelisted), so every string is escaped
// here as well before it reaches YAML.
func renderSubscriptionConfig(opts options) ([]byte, error) {
	if opts.mixedPort == 0 {
		opts.mixedPort = core.DefaultMixedPort
	}
	if opts.apiPort == 0 {
		opts.apiPort = core.DefaultAPIPort
	}
	if len(opts.customProxies) == 0 {
		return nil, fmt.Errorf("订阅模式没有可用节点，请先导入订阅链接、节点链接或配置文件")
	}
	// Subscription mode must not inherit the mixed default resolver list. mihomo
	// queries every nameserver in parallel and takes the fastest answer, so a
	// domestic resolver (lowest RTT by definition) always wins even when it is
	// listed last — and for a CDN front domain it answers with an edge that
	// completes TCP and then returns 502 / fails TLS, which is exactly the
	// "connected but every request 502 Bad Gateway" the user hit.
	//
	// Overseas resolvers only here. The node hostname is resolved through the
	// same list by proxy-server-nameserver, so both paths stay consistent.
	if opts.dns == "" {
		opts.dns = "8.8.8.8, 1.1.1.1"
	}

	base := ""
	for _, p := range opts.customProxies {
		if p.Name == opts.activeProxy {
			base = p.Name
			break
		}
	}
	if base == "" {
		base = opts.customProxies[0].Name
	}

	var b strings.Builder
	b.WriteString("# generated by xehn (subscription mode)\n")
	fmt.Fprintf(&b, "mixed-port: %d\n", opts.mixedPort)
	if opts.psiphonMode {
		fmt.Fprintf(&b, "socks-port: %d\n", underlaySocksPort(opts.mixedPort))
	}
	writeLanBlock(&b, opts)
	fmt.Fprintf(&b, "mode: %s\n", mihomoMode(opts))
	b.WriteString("log-level: info\n")
	fmt.Fprintf(&b, "ipv6: %t\n", opts.ipFamily() != famV4)
	fmt.Fprintf(&b, "external-controller: 127.0.0.1:%d\n", opts.apiPort)
	// Two low-risk mihomo tunings: parallel TCP dials and a single shared
	// health-check scheduler. Neither changes routing semantics.
	b.WriteString("tcp-concurrent: true\nunified-delay: true\n")
	// Same resolver/TUN guarantees as the WARP session: without these, TUN
	// capture had no device and DNS-leak protection did nothing in this mode.
	writeDNSAndTun(&b, opts)

	b.WriteString("proxies:\n")
	writeProxySpecs(&b, opts.customProxies)

	egress := base
	switch {
	case opts.openvpnMode && opts.openvpnNode != nil:
		profile, perr := parseOVPNProfile(opts.openvpnNode.Profile)
		if perr != nil {
			return nil, fmt.Errorf("订阅模式的 OpenVPN 出口配置无效: %w", perr)
		}
		exit := append(mihomoOpenVPNProxy(profile, nestedMTU(opts.mtu)),
			kv{"dialer-proxy", quoted(base)})
		writeYAML(&b, exit, "  ", "- ")
		egress = mihomoOpenVPNName
	case opts.psiphonMode:
		// The Psiphon SOCKS listener is loopback: it must be dialed directly.
		// A dialer-proxy here would reach 127.0.0.1 through the remote node's
		// own loopback and never connect. Psiphon's underlay hop is its
		// UpstreamProxyUrl (the dedicated SUB-BASE SOCKS inbound), not this.
		exit := mihomoSocksProxy(opts.psiphonSocksPort)
		writeYAML(&b, exit, "  ", "- ")
		egress = mihomoPsiphonName
	}

	b.WriteString("\nproxy-groups:\n")
	fmt.Fprintf(&b, "  - name: %s\n    type: select\n    proxies:\n      - %q\n", subBaseGroup, base)
	fmt.Fprintf(&b, "  - name: %s\n    type: select\n    proxies:\n      - %q\n", subExitGroup, egress)
	b.WriteString("rules:\n")
	if opts.psiphonMode {
		// Psiphon's own dials must go out through the subscription base, not
		// back through Psiphon (loop guard), exactly like mode A does.
		fmt.Fprintf(&b, "  - IN-TYPE,SOCKS,%s\n", subBaseGroup)
		fmt.Fprintf(&b, "  - PROCESS-NAME,psiphon.exe,%s\n", subBaseGroup)
	}
	for _, r := range routeRules(opts, subExitGroup) {
		fmt.Fprintf(&b, "  - %s\n", r)
	}
	fmt.Fprintf(&b, "  - MATCH,%s\n", routingFallback(opts, subExitGroup))
	return []byte(b.String()), nil
}

// writeProxySpecs renders the imported proxies (whitelisted fields only) into a
// `proxies:` block. Shared by the session renderer and the throwaway probe core
// so a node that connects also probes identically.
func writeProxySpecs(b *strings.Builder, proxies []ProxySpec) {
	for _, p := range proxies {
		fmt.Fprintf(b, "  - name: %q\n    type: %q\n", p.Name, p.Type)
		keys := make([]string, 0, len(p.Fields))
		for k := range p.Fields {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(b, "    %s: %s\n", k, subYAMLValue(p.Fields[k]))
		}
	}
}

// probeSubscriptionExitConfig is the subscription-mode twin of the WARP probe
// skeleton: imported nodes as the first hop, one OpenVPN relay chained on top,
// MATCH straight to it, and NOTHING else.
//
// It deliberately does not call renderSubscriptionConfig: that one emits the
// session's GEOIP/GEOSITE rules and DNS block, and the probe core runs in an
// empty temp dir with no geodata — mihomo refuses to start there, which is why
// every subscription-mode probe reported "内核未就绪".
func probeSubscriptionExitConfig(o options, profile ovpnProfile, mixedPort, apiPort int) ([]byte, error) {
	if len(o.customProxies) == 0 {
		return nil, fmt.Errorf("订阅模式没有节点可作前置")
	}
	base := o.activeProxy
	found := false
	for _, p := range o.customProxies {
		if p.Name == base {
			found = true
			break
		}
	}
	if !found {
		base = o.customProxies[0].Name
	}
	var b strings.Builder
	fmt.Fprintf(&b, "mixed-port: %d\n", mixedPort)
	b.WriteString("allow-lan: false\nbind-address: 127.0.0.1\n")
	fmt.Fprintf(&b, "external-controller: 127.0.0.1:%d\n", apiPort)
	b.WriteString("mode: rule\nlog-level: info\nipv6: false\n")
	b.WriteString("proxies:\n")
	writeProxySpecs(&b, o.customProxies)
	exit := append(mihomoOpenVPNProxy(profile, 0), kv{"dialer-proxy", quoted(base)})
	writeYAML(&b, exit, "  ", "- ")
	fmt.Fprintf(&b, "rules:\n  - MATCH,%s\n", mihomoOpenVPNName)
	return []byte(b.String()), nil
}

// subYAMLValue renders one whitelisted field as an inline YAML scalar. Maps use
// flow style so nested option blocks (plugin-opts, headers, reality-opts) stay
// legal YAML without hand-written indentation. Strings are always quoted.
func subYAMLValue(v any) string {
	switch t := v.(type) {
	case nil:
		return "null"
	case string:
		return fmt.Sprintf("%q", t)
	case quoted:
		return fmt.Sprintf("%q", string(t))
	case bool:
		return strconv.FormatBool(t)
	case int:
		return strconv.Itoa(t)
	case int64:
		return strconv.FormatInt(t, 10)
	case float64:
		return strconv.FormatFloat(t, 'g', -1, 64)
	case []string:
		parts := make([]string, 0, len(t))
		for _, s := range t {
			parts = append(parts, fmt.Sprintf("%q", s))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case []any:
		parts := make([]string, 0, len(t))
		for _, item := range t {
			parts = append(parts, subYAMLValue(item))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case map[string]any:
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, 0, len(keys))
		for _, k := range keys {
			parts = append(parts, fmt.Sprintf("%q: %s", k, subYAMLValue(t[k])))
		}
		return "{" + strings.Join(parts, ", ") + "}"
	default:
		return fmt.Sprintf("%q", fmt.Sprint(t))
	}
}

// probeCarrierExitConfig is the WARP-mode probe skeleton: the same WARP base
// outbound a real session uses, one OpenVPN relay chained on top, MATCH straight
// to the relay, and nothing else (no geo rules, no DNS block — the probe core
// runs in an empty temp dir with no geodata).
//
// Probing the relay DIRECTLY was the reason a whole 94-node list reported
// failure: VPN Gate relays are frequently reachable only through the tunnel
// (the list itself had to be fetched that way), so a direct SYN or a direct
// OpenVPN handshake dies even though the session would work fine.
func probeCarrierExitConfig(o options, ce cachedEndpoint, run protoRun, prof ovpnProfile, mixedPort, apiPort int) ([]byte, error) {
	ro := o
	ro.confType = confTypeMihomo
	endpoint := ce.Endpoint
	if _, _, err := net.SplitHostPort(endpoint); err != nil {
		endpoint = net.JoinHostPort(endpoint, strconv.Itoa(primaryWarpPorts[0]))
	}
	const baseName = "WARP"
	base, err := mihomoProxy(ro, baseName, endpoint, run, o.mtu, nil)
	if err != nil {
		return nil, err
	}
	exit := append(mihomoOpenVPNProxy(prof, 0), kv{"dialer-proxy", quoted(baseName)})

	var b strings.Builder
	fmt.Fprintf(&b, "mixed-port: %d\n", mixedPort)
	b.WriteString("allow-lan: false\nbind-address: 127.0.0.1\n")
	fmt.Fprintf(&b, "external-controller: 127.0.0.1:%d\n", apiPort)
	b.WriteString("mode: rule\nlog-level: info\nipv6: false\n")
	b.WriteString("proxies:\n")
	writeYAML(&b, base, "  ", "- ")
	writeYAML(&b, exit, "  ", "- ")
	fmt.Fprintf(&b, "rules:\n  - MATCH,%s\n", mihomoOpenVPNName)
	return []byte(b.String()), nil
}

// subscriptionCarrierConfig routes every connection through ONE imported node.
// It is the front hop the VPN Gate list (and its latency probes) must use when
// vpngate.net is blocked directly and the mode forbids building a WARP tunnel:
// the same node the session will use, with the resolver block mihomo needs to
// resolve CDN front domains, and nothing else.
func subscriptionCarrierConfig(proxies []ProxySpec, active string, mixedPort, apiPort int) []byte {
	name := active
	found := false
	for _, p := range proxies {
		if p.Name == name {
			found = true
			break
		}
	}
	if !found && len(proxies) > 0 {
		name = proxies[0].Name
	}
	var b strings.Builder
	fmt.Fprintf(&b, "mixed-port: %d\n", mixedPort)
	b.WriteString("allow-lan: false\nbind-address: 127.0.0.1\n")
	fmt.Fprintf(&b, "external-controller: 127.0.0.1:%d\n", apiPort)
	b.WriteString("mode: rule\nlog-level: info\nipv6: false\n")
	// DNS 必须走隧道，否则整条链路的隐私是假的。
	//
	// 这里原来写的是国内解析器（119.29.29.29 / 223.5.5.5）且没有
	// respect-rules：mihomo 的解析请求因此绕过规则集、直接从本机发出，
	// 检测站看到的解析方就是 China Telecom —— 出口在 US/SG，DNS 在国内，
	// 这是货真价实的泄露（用户实测截图已确认）。
	//
	// 现在：解析器换成 Cloudflare/Google 的任播地址，respect-rules 让解析
	// 请求跟随规则集，下面的 IP-CIDR 再把这两个地址钉到出口节点上。
	// proxy-server-nameserver 仍用国内 DNS：它只负责把节点域名解析成 IP，
	// 不承载任何用户查询。
	b.WriteString("dns:\n  enable: true\n  ipv6: false\n  use-hosts: false\n")
	b.WriteString("  respect-rules: true\n")
	b.WriteString("  nameserver:\n    - 1.1.1.1\n    - 8.8.8.8\n")
	// proxy-server-nameserver resolves the NODE hostname, and a CDN front domain
	// is routed by SNI: the domestic resolvers hand back a Fastly edge that
	// completes the TCP handshake and then fails TLS for this hostname, so the
	// node never connects. 1.1.1.1 answers with the 151.101.x.x anycast set that
	// works; the domestic pair stays as a last resort for networks that block it.
	b.WriteString("  proxy-server-nameserver:\n    - 1.1.1.1\n    - 8.8.8.8\n")
	b.WriteString("proxies:\n")
	writeProxySpecs(&b, proxies)
	fmt.Fprintf(&b, "rules:\n")
	fmt.Fprintf(&b, "  - IP-CIDR,1.1.1.1/32,%s\n", name)
	fmt.Fprintf(&b, "  - IP-CIDR,8.8.8.8/32,%s\n", name)
	fmt.Fprintf(&b, "  - MATCH,%s\n", name)
	return []byte(b.String())
}

// probeCarrierOnlyConfig renders JUST the base protocol, with everything routed
// straight into it. It answers one question before a WARP+exit connect spends
// its relay budget: does this endpoint actually carry traffic?
//
// A dead WireGuard/AWG endpoint still "starts" — the userspace tunnel comes up
// with no error and mihomo reports it healthy — but every dial through it dies.
// The connect then blames the relay: eight combinations, twenty-two seconds
// each, all "handshake timeout", while the relay was fine and only the base was
// dead. Subscription mode never had this problem because its base is a node the
// user already measured.
func probeCarrierOnlyConfig(o options, ce cachedEndpoint, run protoRun, mixedPort, apiPort int) ([]byte, error) {
	ro := o
	ro.confType = confTypeMihomo
	endpoint := ce.Endpoint
	if _, _, err := net.SplitHostPort(endpoint); err != nil {
		endpoint = net.JoinHostPort(endpoint, strconv.Itoa(primaryWarpPorts[0]))
	}
	const baseName = "WARP"
	base, err := mihomoProxy(ro, baseName, endpoint, run, o.mtu, nil)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "mixed-port: %d\n", mixedPort)
	b.WriteString("allow-lan: false\nbind-address: 127.0.0.1\n")
	fmt.Fprintf(&b, "external-controller: 127.0.0.1:%d\n", apiPort)
	b.WriteString("mode: rule\nlog-level: error\nipv6: false\n")
	b.WriteString("proxies:\n")
	writeYAML(&b, base, "  ", "- ")
	fmt.Fprintf(&b, "rules:\n  - MATCH,%s\n", baseName)
	return []byte(b.String()), nil
}
